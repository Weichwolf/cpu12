// Resolve a named opcode prefix at compile time, in guest byte order.
template <Opcode operation> [[nodiscard]] consteval auto opcode() {
  constexpr auto bits = static_cast<std::uint16_t>(operation);
  if constexpr (bits > std::numeric_limits<Byte>::max()) {
    return std::array{static_cast<Byte>(bits >> 8U), static_cast<Byte>(bits)};
  } else {
    return std::array{static_cast<Byte>(bits)};
  }
}

// Concatenate encoded instructions at compile time, with no runtime assembler.
template <std::size_t... sizes>
  requires(sizeof...(sizes) != 0)
[[nodiscard]] consteval auto program(const std::array<Byte, sizes>... instructions) {
  std::array<Byte, (std::size_t{0} + ... + sizes)> result{};
  std::size_t position = 0;
  const auto append = [&](const auto bytes) {
    for (const auto value : bytes) { result[position++] = value; }
  };
  (append(instructions), ...);
  return result;
}

